AGENT_LABEL = 'mcp'


def _run_write_verify(integration, args, res, tool_name, session_id,
                      execution_id, agent_label):
    """Optional post-write read-back: when the generic write tool was given a
    `verify_path` and the write returned 2xx, GET that path and return the
    result (or an error) so the caller sees evidence, not just a status."""
    vpath = (args or {}).get('verify_path')
    status = res.get('status_code')
    if not vpath or not (isinstance(status, int) and 200 <= status < 300):
        return None
    try:
        vres = execute_generic_call(
            integration, 'GET', vpath, (args or {}).get('verify_params'),
            agent=agent_label, tool_name=tool_name + ':verify',
            session_id=session_id, execution_id=execution_id)
    except ProxyError as e:
        return {'error': e.message, 'status_code': e.status_code}
    return {'status_code': vres.get('status_code'), 'body': vres.get('body') or '',
            'error': vres.get('error')}


def _error(msg, status_code=500):
    return json.dumps({'error': msg, 'status_code': status_code})


# Chunk H: a read-only tool must really be read-only. The generic HTTP `read`
# passthrough only sends GET/HEAD, and the generic HA `ws_read` only sends
# reviewed read commands. Both auto-run without an approval, so anything that
# would write must take the approval-gated `write` / `ws_write` path instead.
READ_METHODS = ('GET', 'HEAD')
_READ_TOOL_WRITE_PATH = {'not_a_read_method': 'write',
                         'not_a_read_command': 'ws_write'}


def _normalise_method(method) -> str:
    if method is None:
        return 'GET'
    return (str(method).strip().upper() or 'GET')


def _read_only_refusal(tool, transport, args):
    """(error_code, method-or-command) when a read-only tool is asked to write."""
    if not tool.get('read_only') or not tool.get('generic'):
        return None
    if transport == 'ws':
        command = (args or {}).get('command')
        command = command.strip() if isinstance(command, str) else ''
        if not is_read_command(command):
            return ('not_a_read_command', command)
        return None
    method = _normalise_method((args or {}).get('method'))
    if method not in READ_METHODS:
        return ('not_a_read_method', method)
    return None


def _refuse_read_tool(integration, tool, tool_name, session_id,
                      execution_id, agent_name, error_code, detail):
    """Refuse a write/execute attempt on a read-only tool, and record it.

    The audit row keeps the method/command only — never the payload values —
    and the audit event names the tool so the operator can see an agent that
    tried to write through the read path."""
    transport = tool.get('transport') or 'http'
    write_tool = _READ_TOOL_WRITE_PATH[error_code]
    if error_code == 'not_a_read_method':
        summary = json.dumps({'method': detail}, separators=(',', ':'))
        message = (f"`{tool_name}` only accepts GET or HEAD; {detail} needs the "
                   f"approval-gated `{write_tool}` tool.")
        method, path = detail, ''
        shown = detail
    else:
        summary = json.dumps({'command': detail}, separators=(',', ':'))
        name = detail or '(missing command)'
        message = (f"`{tool_name}` only runs read commands; `{name}` is not one. "
                   f"Use the approval-gated `{write_tool}` tool for it.")
        method, path = 'WS', detail
        shown = name
    record_integration_call(
        integration=integration.get('name', ''),
        tool=tool_name,
        agent=agent_name,
        method=method,
        path=path,
        status_code=400,
        latency_ms=0,
        response_summary=message,
        response_bytes=0,
        truncated=0,
        outcome='refused',
        session_id=session_id,
        execution_id=execution_id,
        reason=f'{error_code}: refused by the read-only tool policy',
        request_summary=summary,
        reason_code=error_code,
    )
    record_audit_event(
        'read_tool_refused',
        details=f"{integration.get('name')}.{tool_name}: {error_code} ({shown})",
        actor=agent_name)
    payload = {'error': error_code, 'message': message,
               'status_code': 400, 'tool': write_tool}
    payload['command' if error_code == 'not_a_read_command' else 'method'] = detail
    return json.dumps(payload)


def _refuse_supervisor_ws(integration, tool, tool_name, args, session_id,
                          execution_id, agent_name, command):
    """F9 R2: the Supervisor is reachable only through `core/ha_supervisor.py`.

    Read/mutate WS commands chosen by an agent must not be able to send
    `supervisor/*` or `hassio/*` at all — one approved `ws_write` would
    otherwise reach host reboot or add-on options, and HA has no allowlist of
    its own. This runs before gating, so no pending call is created either.
    """
    message = ("Supervisor commands are not available through the generic WS "
               "tool. Use the curated ha_supervisor_* tools; their endpoints "
               "are fixed and reviewed.")
    method, path = _request_shape(tool, args, 'ws', bool(tool.get('generic')),
                                  tool.get('handler') or '')
    record_integration_call(
        integration=integration.get('name', ''), tool=tool_name,
        agent=agent_name, method=method, path=path, status_code=403,
        latency_ms=0, response_summary=message, response_bytes=0,
        truncated=0, outcome='refused', session_id=session_id,
        execution_id=execution_id, reason='Supervisor is table-only',
        request_summary=safe_request_summary(args, tool),
        reason_code='supervisor_command_refused')
    record_audit_event(
        'ws_supervisor_refused',
        details=f"{integration.get('name')}.{tool_name}: refused '{command}' "
                f"(Supervisor is table-only)",
        actor=agent_name)
    return json.dumps({'error': 'supervisor_command_refused',
                       'message': message, 'status_code': 403})


_UNGATED_OVERRIDE_WARNED = set()


def _audit_ignored_ungated(agent_name, integration_name, tool_name):
    """P2: tell the operator once per agent and tool that `ungated` did not win.

    `always_gate` is the tool's own promise, not an agent setting, so an
    `ungated` override cannot switch it off. One audit row per pair is enough;
    the tool keeps working as gated either way.
    """
    key = (agent_name, integration_name, tool_name)
    if key in _UNGATED_OVERRIDE_WARNED:
        return
    _UNGATED_OVERRIDE_WARNED.add(key)
    try:
        record_audit_event(
            'mcp_ungated_ignored',
            details=(f"{integration_name}.{tool_name}: the agent's ungated "
                     f"override was ignored; this tool is always gated "
                     f"(agent={agent_name})"))
    except Exception:
        pass


def _refuse_supervisor_rest(integration, tool, tool_name, args, session_id,
                            execution_id, agent_name, path):
    """M1: the Supervisor is reachable only through `core/ha_supervisor.py`.

    HA Core proxies `/api/hassio/…` to the Supervisor and `/api/services/hassio/…`
    runs its services; the curated table alone cannot stop a path chosen by the
    agent. This runs before gating, so no pending call is created either.
    """
    message = ("Supervisor endpoints are not available through the generic REST "
               "tools. Use the curated ha_supervisor_* tools; their endpoints "
               "are fixed and reviewed.")
    method, shown_path = _request_shape(
        tool, args, tool.get('transport') or 'http', bool(tool.get('generic')),
        tool.get('handler') or '')
    record_integration_call(
        integration=integration.get('name', ''), tool=tool_name,
        agent=agent_name, method=method, path=path or shown_path, status_code=403,
        latency_ms=0, response_summary=message, response_bytes=0,
        truncated=0, outcome='refused', session_id=session_id,
        execution_id=execution_id, reason='Supervisor is table-only',
        request_summary=safe_request_summary(args, tool),
        reason_code='supervisor_rest_refused')
    record_audit_event(
        'rest_supervisor_refused',
        details=f"{integration.get('name')}.{tool_name}: refused REST path "
                f"'{path}' (Supervisor is table-only)",
        actor=agent_name)
    return json.dumps({'error': 'supervisor_rest_refused',
                       'message': message, 'status_code': 403})


def _frozen_refusal(integration, tool, tool_name, args, session_id,
                    execution_id, agent_name):
    """F9: Emergency Freeze stops integration writes too.

    Reads keep working (an operator investigating an incident still needs
    them); a handler dry-run changes nothing upstream, so it also runs. The
    refusal is audited like a policy denial, and no upstream call is made.
    """
    message = ('Emergency Freeze is on: SSH and integration writes are paused. '
               'Reads keep working; ask the operator to unfreeze.')
    method, path = _request_shape(
        tool, args, tool.get('transport') or 'http', bool(tool.get('generic')),
        tool.get('handler') or '')
    record_integration_call(
        integration=integration.get('name', ''),
        tool=tool_name,
        agent=agent_name,
        method=method,
        path=path,
        status_code=409,
        latency_ms=0,
        response_summary=message,
        response_bytes=0,
        truncated=0,
        outcome='refused',
        session_id=session_id,
        execution_id=execution_id,
        reason='Emergency Freeze',
        request_summary=safe_request_summary(args, tool),
        reason_code='frozen',
    )
    record_audit_event(
        'mcp_frozen_refused',
        details=f"{integration.get('name')}.{tool_name} refused while frozen",
        actor=agent_name)
    return json.dumps({'error': {'code': 'frozen', 'message': message,
                                 'status_code': 409}})


def _result_error(res: dict) -> str:
    """Surface an upstream failure with a non-2xx status. Omada (and others)
    return logical errors inside an HTTP 200 body; reporting `status_code: 200`
    for a failure is misleading, so normalise any 2xx/missing code to 502.
    A typed `error_obj` (e.g. Omada unknown_site vs permission_denied) is
    preferred over the flat string when present."""
    status = res.get('status_code')
    if not isinstance(status, int) or 200 <= status < 300:
        status = 502
    return json.dumps({'error': res.get('error_obj') or res['error'],
                       'status_code': status})


def _request_shape(tool, args, transport, generic, handler):
    """Best-effort method/path/command for audit rows, before execution."""
    if transport == 'ws':
        return 'WS', (args.get('command') or tool.get('path_template') or '')
    if generic and not handler:
        return (args.get('method') or 'POST'), (args.get('path') or '')
    return (tool.get('method') or 'GET'), (tool.get('path_template') or '')


def _deny(agent_name, integration, tool, tool_name, args, session_id,
          execution_id, reason):
    """Explicit, logged policy refusal. No upstream request is attempted."""
    method, path = _request_shape(
        tool, args, tool.get('transport') or 'http', bool(tool.get('generic')),
        tool.get('handler') or '')
    audit_host = ''
    reason_code = 'policy_denied'
    if tool.get('handler') == 'web_fetch':
        # Never persist the requested URL's query values: they may carry
        # household data. Host + path is enough to explain the denial.
        try:
            from core.web_fetch_policy import parse_url
            parsed = parse_url((args or {}).get('url') or '')
            audit_host = parsed.host
            path = parsed.host + parsed.path
            request_summary = json.dumps(
                {'host': parsed.host, 'path': parsed.path,
                 'query_present': bool(parsed.query)},
                separators=(',', ':'))
        except Exception:
            request_summary = '{}'
        if 'principal' in (reason or ''):
            reason_code = 'principal_not_allowed'
        elif 'allowlist' in (reason or ''):
            reason_code = 'tool_not_allowed'
    else:
        request_summary = safe_request_summary(args, tool)
    summary = 'Denied by agent policy: ' + reason
    record_audit_event(
        'mcp_policy_denied',
        details=f"{integration.get('name')}.{tool_name}: {reason}",
        actor=agent_name)
    record_integration_call(
        integration=integration.get('name', ''),
        tool=tool_name,
        agent=agent_name,
        method=method,
        path=path,
        status_code=0,
        latency_ms=0,
        response_summary=summary,
        response_bytes=0,
        truncated=0,
        outcome='denied',
        session_id=session_id,
        execution_id=execution_id,
        reason=reason,
        request_summary=request_summary,
        approval='denied',
        host=audit_host,
        reason_code=reason_code,
    )
    return json.dumps({
        'error': 'forbidden',
        'reason': reason,
        'policy': agent_name,
    })


def resolve_session(explicit: str = ''):
    """Resolve the id for one call, and say where it came from.

    An explicit `session_id` always wins. Otherwise the id `session_begin`
    bound to this connection is inherited, so "name it once, then forget"
    still groups the rest of the task. Only if the connection never named a
    session does the call fall back to the transport bucket (`mcp-…`), which
    is the honest "no session was named" case.
    """
    explicit = (explicit or '')[:64]
    if explicit:
        return explicit, 'caller'
    inherited = last_session_for_transport()
    if inherited:
        return inherited, 'inherited'
    transport = current_session_id()
    return transport, ('transport' if transport else '')


def run_tool(integration_name: str, tool_name: str, args: dict, reason: str = '') -> str:
    """Run one tool call, and tell the model which session it landed in.

    The caller's own `session_id` argument always wins. When it is missing, the
    id from `session_begin` (remembered per connection) is inherited; only if
    that connection never named a session does the call fall back to the
    transport bucket. The result says which id it used and where it came from.
    """
    supplied = ((args or {}).get('session_id') or '')[:64]
    sid, source = resolve_session(supplied)
    # Strict mode: no named, minted session means no tool execution. The
    # built-ins (session_begin / session_summary / check_approval) do not go
    # through run_tool, so the agent can always recover.
    if require_sessions_enabled():
        problem = session_problem(sid)
        if problem:
            record_audit_event(
                'mcp_session_required',
                details=f'{integration_name}.{tool_name}: {problem}')
            return json.dumps({
                'error': 'session_required',
                'message': problem,
                'session_id': sid,
            })
    source_token = set_current_session_source(source)
    try:
        result = _run_tool(integration_name, tool_name, args, reason,
                           session_id=sid, session_source=source)
    finally:
        reset_current_session_source(source_token)
    if supplied:
        remember_session_for_transport(supplied)
        return result
    return _annotate_session(result, sid, source) if sid else result


def _annotate_session(result: str, session_id: str,
                      source: str = 'transport') -> str:
    """Add `_eshu.session_id` to a JSON object result. Never mutates arrays or
    non-JSON payloads — an annotation is a courtesy, not a payload change."""
    try:
        data = json.loads(result)
    except Exception:
        return result
    if not isinstance(data, dict) or '_eshu' in data:
        return result
    data['_eshu'] = {'session_id': session_id,
                     'source': source or 'transport'}
    return json.dumps(data)


def _run_tool(integration_name: str, tool_name: str, args: dict, reason: str = '',
              session_id: str = None, session_source: str = '') -> str:
    """Execute (or gate) one MCP tool call and return the JSON string for the model."""
    integration = get_integration(integration_name)
    if not integration or not integration.get('enabled'):
        return _error("Integration not found or disabled", 404)
    tool = get_tool(integration_name, tool_name)
    if not tool or not tool.get('enabled'):
        return _error("Tool not found or disabled", 404)

    args = args or {}
    # Phase 2: MCP tool calls accept structured session_id / execution_id so the
    # dashboard groups them with SSH commands from the same agent conversation.
    # Popped here so they never reach the upstream API as forwarded params.
    explicit = (args.pop('session_id', '') or '')[:64]
    if session_id is None:
        session_id, session_source = resolve_session(explicit)
    execution_id = (args.pop('execution_id', '') or '')[:64]

    agent = get_current_agent()
    agent_name = (agent or {}).get('name') or AGENT_LABEL

    # Agent policy is the first gate: deny-by-default tool allowlist followed by
    # argument constraints (e.g. HA service domains). A denial is explicit and
    # audited; it never reaches create_pending_call() or the upstream API.
    allowed, deny_reason = evaluate_call(
        agent, integration['name'], tool_name, args,
        tool=tool, integration=integration)
    if not allowed:
        return _deny(agent_name, integration, tool, tool_name, args,
                     session_id, execution_id, deny_reason)

    if tool.get('not_implemented'):
        return json.dumps({'error': 'not_implemented',
                           'message': f"{tool_name} is declared in the catalog "
                                      "but not implemented yet",
                           'status_code': 501})
    transport = tool.get('transport') or 'http'
    generic = bool(tool.get('generic'))
    mutating = not tool.get('read_only')
    handler = tool.get('handler') or ''
    # F9: Emergency Freeze covers integration writes as well as SSH. Whether
    # this call is a read comes from the §2.6a policy, not from a second local
    # notion. Only a *handler* dry-run is exempt: `dry_run` is a real argument
    # on curated handlers (they honour it), but on a REST/WS/generic tool it is
    # just one more argument — the same condition the gate below uses.
    if get_trigger_freeze() and not (handler and args.get('dry_run')):
        # Imported here: read_policy wraps _read_only_refusal from this module,
        # so a top-level import would be a cycle.
        from core.read_policy import is_read_integration_call
        is_read, _why = is_read_integration_call(
            tool, tool.get('transport') or 'http', args)
        if not is_read:
            return _frozen_refusal(integration, tool, tool_name, args,
                                   session_id, execution_id, agent_name)
    # F10: `call_service(domain='hassio', …)` reaches the Supervisor powers the
    # F10 tools gate one by one, outside that table. Refuse it unless the agent's
    # own policy names `hassio` explicitly (the operator's audited escape hatch).
    if tool_name == 'call_service' and \
            str((args or {}).get('domain') or '').strip().lower() == 'hassio':
        from core.agent_policy import explicit_hassio_allowed
        if not explicit_hassio_allowed(agent, integration['name'], tool_name):
            record_audit_event(
                'hassio_domain_refused', details=(
                    f"{integration['name']}.{tool_name}: domain=hassio refused; "
                    f"use the F10 Supervisor tools (agent={agent_name})"))
            return json.dumps({
                'error': 'hassio_domain_refused',
                'message': ('domain=hassio is refused by default: use the F10 '
                            'Supervisor tools (ha_addon_action, ha_addon_update, '
                            'ha_core_update, ha_backup_create, ha_core_restart, '
                            'ha_host_reboot), which are approval-gated. An operator '
                            'can allow hassio for this agent explicitly.'),
                'status_code': 403,
            })
    # Chunk H: the read-only passthrough tools auto-run, so they must not be
    # able to write or execute. This runs whatever the agent's policy says; an
    # arg_policy still applies on top for the calls that do get through.
    refusal = _read_only_refusal(tool, transport, args)
    if refusal is not None:
        return _refuse_read_tool(integration, tool, tool_name,
                                 session_id, execution_id, agent_name, *refusal)
    # F9 R2: the generic WS tools must never send a Supervisor command.
    if transport == 'ws':
        command = (args or {}).get('command') or tool.get('path_template') or ''
        if is_supervisor_command(command):
            return _refuse_supervisor_ws(integration, tool, tool_name, args,
                                         session_id, execution_id, agent_name,
                                         str(command))
    # F10 M1: the same rule for HA's REST surface. `/api/hassio/…` is HA Core's
    # Supervisor proxy and `/api/services/hassio/…` the Supervisor's services.
    # A generic path is chosen by the agent, so the static FORBIDDEN scan
    # cannot see it; this runs before gating, and the executors re-check.
    _ha_path = ''
    if (integration.get('kind') or '').lower() == 'ha' and transport == 'http':
        _method, _path = _request_shape(tool, args, transport, generic, handler)
        _ha_path = str(_path)
        # S-a: check the path the request will carry, including the
        # integration's own base path, not only the tool's part.
        if is_supervisor_rest_request(integration.get('base_url'), _path):
            return _refuse_supervisor_rest(integration, tool, tool_name, args,
                                           session_id, execution_id, agent_name,
                                           _ha_path)
    # Audit labels: an immediate mutating call ran without operator sign-off
    # ("auto"); reads and handler dry-runs are not approval-relevant.
    approval_label = 'auto' if (mutating and not args.get('dry_run')) else ''
    exec_reason = reason if mutating else ''
    # (the plan claim below may replace approval_label with the plan reference)

    def _execute():
        if handler:
            # Curated multi-step handler — returns the final JSON string itself.
            from core.tool_handlers import run_handler
            return run_handler(handler, integration, tool, args,
                               agent=agent_name, session_id=session_id,
                               execution_id=execution_id,
                               reason=exec_reason, approval=approval_label)
        if transport == 'ws':
            # WS tools (curated registry tools or generic ws tools) run the
            # command from path_template / the command arg.
            command = tool.get('path_template') or args.get('command') or ''
            payload = args.get('payload')
            return execute_ws_call(integration, command, payload,
                                   agent=agent_name, tool_name=tool_name,
                                   session_id=session_id, execution_id=execution_id,
                                   reason=exec_reason, approval=approval_label)
        if generic:
            return execute_generic_call(
                integration, args.get('method'), args.get('path'),
                args.get('params'), args.get('data'),
                agent=agent_name, tool_name=tool_name, root=bool(args.get('root')),
                session_id=session_id, execution_id=execution_id,
                reason=exec_reason, approval=approval_label,
                read_only=not mutating)
        return execute_integration_call(integration, tool, args, agent=agent_name,
                                        session_id=session_id, execution_id=execution_id,
                                        reason=exec_reason, approval=approval_label)

    # Read-only: always execute (auto-run + audit) and shape client-side.
    if not mutating:
        try:
            res = _execute()
        except ProxyError as e:
            return _error(e.message, e.status_code)
        if handler:
            return res
        if res.get('error'):
            return _result_error(res)
        if tool.get('transform') and transport != 'ws':
            # execute_integration_call already ran the registered transform —
            # shaping it again would double-apply (e.g. charts downsample).
            # WS tools do NOT run transforms in execute_ws_call, so they fall
            # through to _apply_shaping below.
            return res['body']
        return _apply_shaping(res['body'], tool, args, integration)

    # Mutating: consult the agent override first, then the integration policy.
    method, path = _request_shape(tool, args, transport, generic, handler)
    destructive = is_destructive(method, path)
    gate_mode = (integration.get('gate_mode') or 'destructive').lower()
    should_gate = (gate_mode == 'all'
                   or (gate_mode == 'destructive' and destructive)
                   or bool(tool.get('always_gate')))
    if agent:
        mode = approval_mode(agent, integration['name'], tool_name)
        if mode == 'gated':
            should_gate = True
        elif mode == 'ungated':
            # P2: `always_gate` wins. An agent policy (`ha.*: ungated`, `*:
            # ungated`, or an exact key) can no longer switch off the gate on
            # a Supervisor action; a plan is the one way to pre-approve one,
            # and the reboot never can be. The override is audited once per
            # agent and tool so the operator learns why it had no effect.
            if tool.get('always_gate'):
                _audit_ignored_ungated(agent_name, integration['name'], tool_name)
            else:
                should_gate = False
    # S-b: an approved write to HA's automation/script/scene config API can
    # define an action that calls any hassio.* service. The path is not
    # FORBIDDEN, so the card must carry the same red line as the reboot.
    config_warning = ''
    if _ha_path and mutating and is_admin_config_write(_ha_path):
        config_warning = ('⚠ Admin power: this config write can define an action '
                          'that calls any Supervisor (hassio.*) service.')
    # A handler dry-run never writes upstream, so it runs pre-gate regardless
    # of the tool's or agent's gating policy.
    if handler and args.get('dry_run'):
        should_gate = False

    # F10/F3: an approved Session plan can cover an MCP call. Matching is by
    # integration + tool + the exact argument hash, one use per claim — the
    # same rule as SSH plan items, never a pattern.
    plan_approval = ''
    if should_gate and session_id:
        from db.session_plans import (PlanError, args_hash,
                                      claim_mcp_plan_item)
        try:
            # M2: the claim is bound to the session's owner; an ownerless
            # session (or no authenticated agent) matches nothing.
            claimed = claim_mcp_plan_item(
                session_id, integration['name'], tool_name, args_hash(args),
                owner=(agent or {}).get('name') or '')
        except PlanError:
            claimed = None
        if claimed:
            should_gate = False
            plan_approval = 'session-plan:%d:%d' % claimed
            approval_label = plan_approval
            record_audit_event(
                'jit_plan_approved', details=(
                    f'Session plan #{claimed[0]} item #{claimed[1]} approved '
                    f'{integration["name"]}.{tool_name} (session {session_id})'))

    if should_gate:
        if handler:
            # Validate the write (read → patch → diff, no write) before queuing
            # an approval, so an operator never spends an approval on a write
            # that cannot succeed.
            from core.tool_handlers import run_preflight
            pre = run_preflight(handler, integration, tool, args,
                                agent=agent_name, session_id=session_id,
                                execution_id=execution_id)
            if isinstance(pre, dict):
                # F10: a viable action may hand back the summary the approval
                # card shows. Anything else keeps the old "error string or None".
                summary = str(pre.get('_summary') or '')
                if config_warning:
                    summary = (config_warning + ' ' + summary).strip()
                call_id = create_pending_call(
                    integration['name'], tool_name, args, reason,
                    session_id=session_id, execution_id=execution_id,
                    agent=agent_name, session_source=session_source,
                    summary=summary)
                from core.notify import send_notify
                send_notify('jit', 'API Approval Required',
                            '`%s` on %s by %s: ' % (tool_name, integration_name, agent_name)
                            + (summary or reason or '')[:80])
                return json.dumps({'status': 'pending', 'id': call_id,
                                   'message': 'Awaiting operator approval. Call check_approval(%d) to poll.' % call_id})
            if pre is not None:
                return pre
        call_id = create_pending_call(
            integration['name'], tool_name, args, reason,
            session_id=session_id, execution_id=execution_id, agent=agent_name,
            session_source=session_source, summary=config_warning)
        from core.notify import send_notify
        send_notify('jit', 'API Approval Required',
                    '`%s` on %s by %s: ' % (tool_name, integration_name, agent_name)
                    + (reason or '')[:80])
        return json.dumps({'status': 'pending', 'id': call_id,
                           'message': 'Awaiting operator approval. Call check_approval(%d) to poll.' % call_id})

    try:
        res = _execute()
    except ProxyError as e:
        return _error(e.message, e.status_code)
    if handler:
        return res
    if res.get('error'):
        return _result_error(res)
    if generic:
        # Never report a bare 2xx/204 as success: return the response plus the
        # request shape, flag an empty body as unverified, and attach the
        # optional read-back.
        verified = _run_write_verify(integration, args, res, tool_name,
                                     session_id, execution_id, agent_name)
        return generic_write_envelope(res, method, path, args.get('data'),
                                      verified=verified)
    return merge_response_hint(tool, res['body'])
